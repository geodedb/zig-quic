#!/bin/bash

# QUIC Handshake Analysis Script
# Analyzes the handshake failure between Zig server and quic-go client

LOG_DIR="/home/benji/src/spyder/quic/test-logs"
CLIENT_LOG="$LOG_DIR/client.log"
SERVER_LOG="$LOG_DIR/server.log"

echo "========================================"
echo "QUIC HANDSHAKE FAILURE ANALYSIS"
echo "========================================"
echo ""

echo "CLIENT LOG ANALYSIS:"
echo "--------------------"
echo ""

echo "1. Initial Handshake - Client sends ClientHello:"
grep "-> &wire.CryptoFrame" "$CLIENT_LOG" | head -2
echo ""

echo "2. Client receives ACK from server:"
grep "newly acked packets" "$CLIENT_LOG" | head -1
echo ""

echo "3. Critical Issue - Coalesced packet parsing:"
grep "coalesced packet has different destination connection ID" "$CLIENT_LOG" | wc -l
echo "   ^ Number of times coalesced packet was rejected"
echo ""

echo "4. Client timeout after repeated PINGs:"
grep "-> &wire.PingFrame" "$CLIENT_LOG" | wc -l
echo "   ^ Number of PING frames sent (client trying to keep connection alive)"
echo ""

echo "5. Final error:"
grep "Failed to dial" "$CLIENT_LOG"
echo ""

echo ""
echo "SERVER LOG ANALYSIS:"
echo "--------------------"
echo ""

echo "1. Server derives Initial secrets successfully:"
grep "deriveKeyIvHp: secret" "$SERVER_LOG" | head -2
echo ""

echo "2. Server derives Handshake secrets:"
grep "deriveKeyIvHp: secret" "$SERVER_LOG" | tail -2
echo ""

echo "3. Server reports connection accepted:"
grep "accepted connection" "$SERVER_LOG"
echo ""

echo ""
echo "========================================"
echo "ROOT CAUSE ANALYSIS"
echo "========================================"
echo ""

echo "PROBLEM IDENTIFIED:"
echo "-------------------"
echo ""
echo "The quic-go client is receiving coalesced packets from the Zig server,"
echo "but the coalesced Handshake packet has an incorrect destination connection ID."
echo ""
echo "From client logs:"
grep "coalesced packet has different destination connection ID" "$CLIENT_LOG" | head -1
echo ""
echo "Expected behavior:"
echo "  - Server sends Initial packet with ACK (successfully received)"
echo "  - Server coalesces Handshake packet in the same datagram"
echo "  - Handshake packet should have destination connection ID: (empty)"
echo "  - But it has: 8bd1f6093ae7540c (the server's source connection ID)"
echo ""
echo "This mismatch causes the client to reject the Handshake packet,"
echo "preventing it from decrypting the server's Handshake messages."
echo ""
echo "Consequence:"
echo "  - Client never receives server's Certificate/CertificateVerify/Finished"
echo "  - Client cannot complete TLS handshake"
echo "  - Client times out after sending PINGs"
echo ""

echo ""
echo "========================================"
echo "TECHNICAL DETAILS"
echo "========================================"
echo ""

echo "Packet sequence:"
echo "----------------"
echo ""
echo "1. Client -> Server: Initial[0] (ClientHello part 1)"
echo "2. Client -> Server: Initial[1] (ClientHello part 2)"
echo "3. Server -> Client: Initial[1] + Handshake[?]"
echo "   - Initial packet: OK (contains ACK)"
echo "   - Handshake packet: REJECTED (wrong dest conn ID)"
echo ""

echo "Connection ID usage:"
echo "--------------------"
echo ""
echo "From client log:"
grep "Starting new connection" "$CLIENT_LOG"
grep "Received first packet. Switching destination connection ID" "$CLIENT_LOG"
echo ""
echo "Client's destination CID: ed85df6cdef9d482c56b9e7f2ac16ca6 (initial)"
echo "                      ->: 8bd1f6093ae7540c (after receiving server's Initial)"
echo "Server's source CID: 8bd1f6093ae7540c"
echo ""
echo "Problem: Coalesced Handshake packet uses destination CID 8bd1f6093ae7540c"
echo "         but quic-go expects (empty) for coalesced packets in same datagram"
echo ""

echo ""
echo "========================================"
echo "RFC 9000 COMPLIANCE CHECK"
echo "========================================"
echo ""
echo "RFC 9000 Section 12.2 - Coalescing Packets:"
echo ""
echo "  'Senders MUST NOT coalesce QUIC packets with different connection IDs"
echo "   into a single UDP datagram.'"
echo ""
echo "The server is violating this by coalescing an Initial packet (with empty"
echo "destination CID) and a Handshake packet (with non-empty destination CID)"
echo "in the same UDP datagram."
echo ""

echo ""
echo "========================================"
echo "RECOMMENDED FIX"
echo "========================================"
echo ""
echo "In the Zig QUIC server code, when coalescing Initial and Handshake packets:"
echo ""
echo "1. Ensure the Handshake packet uses the same destination connection ID"
echo "   as the Initial packet (which should be empty at this stage)"
echo ""
echo "2. Or, send the Handshake packet in a separate UDP datagram"
echo ""
echo "3. The destination connection ID in the Handshake packet should be:"
echo "   - Empty (if the client didn't provide a source CID in Initial)"
echo "   - Or the client's source CID (if one was provided)"
echo ""
echo "The server should NOT use its own source CID as the destination CID"
echo "in packets sent to the client."
echo ""

echo ""
echo "========================================"
echo "NEXT STEPS"
echo "========================================"
echo ""
echo "1. Examine the Zig server's packet coalescing logic"
echo "2. Check how destination connection IDs are set for Handshake packets"
echo "3. Verify connection ID mapping when transitioning from Initial to Handshake"
echo "4. Add logging to show the destination CID used in each packet"
echo "5. Test fix with this same quic-go client"
echo ""
