const std = @import("std");
const conn_mod = @import("../src/quic/conn.zig");
const packet = @import("../src/quic/packet.zig");
const tp = @import("../src/quic/transport_params.zig");
const handshake_integration = @import("../src/quic/endpoint/handshake_integration.zig");

test "initial crypto handles overlapping frames" {
    const allocator = std.testing.allocator;

    var conn = conn_mod.Connection{};
    defer conn.deinit();

    var sock = conn_mod.SockAddr{};
    conn.init(&allocator, .Server, -1, sock);
    // NOTE: allow_insecure is handled via TLS Context configuration
    conn.version = packet.QUIC_V1;
    conn.version_v2 = false;

    // Configure minimal local transport parameters required for ServerHello.
    var params: tp.TransportParams = .{};
    params.initial_max_data = 0x10000;
    const tp_bytes = try tp.TransportParams.encode(&params, allocator);
    defer allocator.free(tp_bytes);
    try conn.setLocalTransportParameters(tp_bytes);

    // Provide a deterministic server connection ID for testing.
    conn.our_scid.len = 8;
    std.mem.copy(u8, conn.our_scid.bytes[0..8], &.{ 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08 });

    const client_hello = [_]u8{
        0x01, 0x00, 0x00, 0x8C, 0x03, 0x03, 0xD8, 0xFC,
        0x30, 0x13, 0xDD, 0x40, 0xB0, 0xFD, 0xE1, 0xB1,
        0xA4, 0x99, 0xCE, 0x40, 0x96, 0xB9, 0xEB, 0xB0,
        0x75, 0x98, 0x85, 0x14, 0x6E, 0x12, 0xF3, 0x63,
        0x65, 0x67, 0x1B, 0xE4, 0x29, 0x85, 0x00, 0x00,
        0x02, 0x13, 0x01, 0x01, 0x00, 0x00, 0x61, 0x00,
        0x2B, 0x00, 0x03, 0x02, 0x03, 0x04, 0x00, 0x0A,
        0x00, 0x04, 0x00, 0x02, 0x00, 0x1D, 0x00, 0x0D,
        0x00, 0x08, 0x00, 0x06, 0x04, 0x03, 0x08, 0x04,
        0x08, 0x07, 0x00, 0x33, 0x00, 0x26, 0x00, 0x24,
        0x00, 0x1D, 0x00, 0x20, 0xC5, 0x27, 0xA0, 0xB4,
        0xA6, 0x6B, 0x47, 0x2F, 0xA3, 0xCE, 0xC3, 0x68,
        0xED, 0xC0, 0xDE, 0x9B, 0x93, 0xC2, 0xF7, 0xAC,
        0xD3, 0xD2, 0x99, 0x05, 0x55, 0x55, 0x66, 0x18,
        0x17, 0x08, 0xD1, 0x31, 0x00, 0x39, 0x00, 0x18,
        0x04, 0x04, 0x80, 0x04, 0x00, 0x00, 0x05, 0x04,
        0x80, 0x01, 0x00, 0x00, 0x06, 0x04, 0x80, 0x01,
        0x00, 0x00, 0x08, 0x01, 0x10, 0x09, 0x01, 0x00,
    };

    const partial_len: usize = 60;

    // Set up threadlocal for TLS Context callbacks
    handshake_integration.setCurrentConnection(&conn);
    defer handshake_integration.clearCurrentConnection();

    const ack1 = try conn.handleInitialCrypto(&allocator, 0, client_hello[0..partial_len]);
    try std.testing.expect(ack1);
    try std.testing.expectEqual(@as(u64, partial_len), conn.crypto_rx_off_initial);

    const ack2 = try conn.handleInitialCrypto(&allocator, 0, client_hello[0..]);
    try std.testing.expect(ack2);
    try std.testing.expectEqual(@as(u64, client_hello.len), conn.crypto_rx_off_initial);
    try std.testing.expect(conn.hs_client != null);
    try std.testing.expect(conn.hs_server != null);
}
